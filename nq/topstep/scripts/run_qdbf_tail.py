#!/usr/bin/env python
"""Pre-registered ONE-SHOT virgin-tail confirmation: qdbF_L_r0.6_mnqa only.

PRE-REGISTRATION (frozen before evaluation; no iteration afterward):
  Rule: qdbF_L_r0.6_mnqa exactly as generated by exec_micro_grids()[1] —
  LONG 4 MNQ on a top-decile 10s delta-burst against a bottom-decile fast-z
  flush (trailing 20-session quantiles), ATR band 4-40 ticks, spread guard;
  stop 3xATR, target 1.8xATR (0.6R), 25-bar time stop, max 4 trades/day,
  day stop -$760 (worst risk $240 <= $1,000/4).
  Tail: 2025-01-02 .. 2025-06-30 (never used by any prior selection).
  HARD GATES: win >= 0.55 | trades/session >= 1.0 | net > 0 |
  chain-MC EV/month > 0 | blowout < 0.50 | zero violations | audits PASS.
  Verdict = ALL gates. Single evaluation.

Writes outputs/qdbf_tail_confirmation.{md,json}.
"""
from __future__ import annotations

import json
import sys
import time as _time
from dataclasses import asdict
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from tslab.audit.leakage import Status, TruncationInvarianceCheck  # noqa: E402
from tslab.config import load_config                               # noqa: E402
from tslab.features.core import FeatureParams                      # noqa: E402
from tslab.features.quantiles import compute_micro_q_features      # noqa: E402
from tslab.sim.costs import CostModel                              # noqa: E402
from tslab.strategy.backtest import run_backtest                   # noqa: E402
from tslab.strategy.evaluate import (lifecycle_mc_chain,           # noqa: E402
                                     max_drawdown, simulate_account)
from tslab.strategy.rules import exec_micro_grids                  # noqa: E402

RULE = "qdbF_L_r0.6_mnqa"
TAIL_START, TAIL_END = date(2025, 1, 1), date(2025, 6, 30)
GATES = {"win": 0.55, "tps": 1.0, "blowout": 0.50}


def main() -> int:
    t0 = _time.time()
    cfg = load_config()
    outdir = cfg.paths.outputs_dir
    fp = FeatureParams()
    _, grid_mnq = exec_micro_grids()
    rule = next(r for r in grid_mnq if r.name == RULE)
    prereg = {"rule_name": RULE, "gates": GATES,
              "tail": [str(TAIL_START), str(TAIL_END)],
              "rule": {**{k: str(v) for k, v in asdict(rule).items()
                          if k != "filters"},
                       "filters": [asdict(f) for f in rule.filters]}}
    (outdir / "qdbf_tail_prereg.json").write_text(json.dumps(prereg, indent=2))
    print(f"pre-registered {RULE}; evaluating ONCE on "
          f"{TAIL_START}..{TAIL_END}", flush=True)

    full = pd.read_parquet(outdir / "nq_micro_bars_full.parquet")
    feats = compute_micro_q_features(full, cfg, fp)

    def sig_fn(df):
        fe = compute_micro_q_features(df, cfg, fp)
        return pd.DataFrame({"sig": rule.entry_signal(fe, cfg).astype(float)},
                            index=df.index)

    aud = TruncationInvarianceCheck(full, sig_fn, n_probes=4).run()
    aud.name = f"signal_truncation:{RULE}"
    print(f"  [{aud.status.value}] {aud.name}", flush=True)

    ta = full["session"].isin(
        [s for s in set(full["session"]) if TAIL_START <= s <= TAIL_END]
    ).to_numpy()
    bta, fta = full[ta], feats[ta]
    tail_sessions = sorted(set(bta["session"]))
    bt = run_backtest(rule, bta, fta, cfg, CostModel(cfg), instrument="MNQ")
    daily = bt.daily_net().reindex(tail_sessions).fillna(0.0)
    n = len(bt.trades)
    wins = sum(1 for t in bt.trades if t.net_usd > 0)
    stats = {
        "trades": n, "tps": n / len(tail_sessions),
        "win_rate": wins / n if n else float("nan"),
        "net": round(bt.total_net, 1),
        "gross": round(sum(t.gross_usd for t in bt.trades), 1),
        "costs": round(sum(t.costs_usd for t in bt.trades), 1),
        "avg_win": round(float(np.mean([t.net_usd for t in bt.trades
                                        if t.net_usd > 0])), 1) if wins else 0,
        "avg_loss": round(float(np.mean([t.net_usd for t in bt.trades
                                         if t.net_usd <= 0])), 1)
        if n > wins else 0,
        "max_dd": round(max_drawdown(daily), 1),
        "violations": bt.violations,
    }
    acct = simulate_account(bt.by_session(), cfg, size="50k",
                            personal_dll=1000.0) if n else None
    pool = {s: [] for s in tail_sessions}
    for t in bt.trades:
        pool[t.session].append(t)
    mc = lifecycle_mc_chain([pool[s] for s in tail_sessions], cfg,
                            n_runs=300, horizon_sessions=252)

    gate = {
        "win_rate": bool(n and stats["win_rate"] >= GATES["win"]),
        "frequency": stats["tps"] >= GATES["tps"],
        "net_positive": bt.total_net > 0,
        "ev_month_positive": mc.ev_month > 0,
        "blowout": mc.blowout_rate < GATES["blowout"],
        "zero_violations": bt.violations == 0,
        "audits_pass": aud.status != Status.FAIL,
    }
    passed = all(gate.values())

    out = {
        "prereg": prereg, "stats": stats,
        "account": None if acct is None else {
            "phase": acct.phase, "dll_hits": acct.dll_hits,
            "mll_events": [e for e in acct.events if e[0] == "MLL_BREACH"]},
        "chain_mc": {k: (round(v, 4) if isinstance(v, float) else v)
                     for k, v in vars(mc).items()},
        "gates": gate, "passed": bool(passed),
        "runtime_min": round((_time.time() - t0) / 60, 1),
    }
    (outdir / "qdbf_tail_confirmation.json").write_text(
        json.dumps(out, indent=2, default=str))
    md = [f"# One-shot virgin-tail confirmation: {RULE}", "",
          f"**PASSED: {passed}**", "",
          f"- tail {TAIL_START}..{TAIL_END}: {len(tail_sessions)} sessions",
          f"- trades {n} ({stats['tps']:.2f}/session), win "
          f"{stats['win_rate']:.3f}, net ${stats['net']:,} "
          f"(gross ${stats['gross']:,} costs ${stats['costs']:,})",
          f"- avg win ${stats['avg_win']} / loss ${stats['avg_loss']}, "
          f"maxDD ${stats['max_dd']:,}",
          f"- chain MC: EV/mo ${mc.ev_month:,.0f}, blowout "
          f"{mc.blowout_rate:.2f}, P(pay1/2/3) {mc.p_payout1:.2f}/"
          f"{mc.p_payout2:.2f}/{mc.p_payout3:.2f}, P(pass) {mc.p_pass:.2f}, "
          f"DLL rate {mc.dll_hit_rate:.3f}",
          f"- account pass: {out['account']}",
          "", "| gate | result |", "|---|---|"]
    md += [f"| {k} | {'PASS' if v else 'FAIL'} |" for k, v in gate.items()]
    (outdir / "qdbf_tail_confirmation.md").write_text("\n".join(md))
    print(json.dumps({"passed": passed, "gates": gate, "stats": stats,
                      "ev_month": round(mc.ev_month, 1),
                      "blowout": round(mc.blowout_rate, 3)}, indent=2),
          flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
